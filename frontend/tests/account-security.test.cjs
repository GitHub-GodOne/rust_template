const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const test = require("node:test");
const vm = require("node:vm");
const ts = require("typescript");
const { convert, scopeSelector } = require("../scripts/build-dark-theme.cjs");

function load(relative) {
  const source = fs.readFileSync(path.join(__dirname, "..", relative), "utf8");
  const compiled = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  const output = { exports: {} };
  vm.runInNewContext(compiled, { exports: output.exports });
  return output.exports;
}

const { describeUserAgent } = load("src/utils/userAgent.ts");

test("session devices are labelled browser · OS", () => {
  assert.equal(
    describeUserAgent(
      "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/129.0.0.0 Safari/537.36",
    ),
    "Chrome 129 · Windows",
  );
  assert.equal(
    describeUserAgent(
      "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/129.0.0.0 Safari/537.36 Edg/129.0.0.0",
    ),
    "Edge 129 · Windows",
  );
  assert.equal(
    describeUserAgent(
      "Mozilla/5.0 (iPhone; CPU iPhone OS 17_5 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.5 Mobile/15E148 Safari/604.1",
    ),
    "Safari 17 · iOS",
  );
  assert.equal(describeUserAgent("curl/8.4.0"), "curl");
  assert.equal(describeUserAgent(null), "");
});

test("dark theme flips light surfaces and dark text, keeps dark parts", () => {
  const lightness = (hex) => {
    const [r, g, b] = [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16) / 255);
    return (Math.max(r, g, b) + Math.min(r, g, b)) / 2;
  };
  assert.ok(lightness(convert("#ffffff", "surface")) < 0.2, "white background turns dark");
  assert.ok(lightness(convert("#292622", "ink")) > 0.75, "dark text turns light");
  assert.equal(convert("#050505", "surface"), null, "terminal black stays");
  assert.equal(convert("#ffffff", "ink"), null, "white text on color stays");
  assert.equal(convert("#c15f3c", "surface"), null, "accent fills stay");
  assert.match(convert("rgba(255, 255, 255, 0.72)", "surface"), /^rgba\(.*0\.72\)$/);
  assert.equal(
    scopeSelector(".a, :root .b, html"),
    ':root[data-theme="dark"] .a,\n:root[data-theme="dark"] .b,\n:root[data-theme="dark"]',
  );
});

test("the committed dark stylesheet is up to date", () => {
  const generated = fs.readFileSync(path.join(__dirname, "../src/styles/dark-theme.css"), "utf8");
  assert.match(generated, /Generated by scripts\/build-dark-theme\.cjs/);
  assert.match(generated, /:root\[data-theme="dark"\] \.admin-card/);
});
